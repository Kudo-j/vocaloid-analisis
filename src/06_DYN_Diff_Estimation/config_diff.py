# =============================================================================
# 時間差分モデルによる DYN推定 設定ファイル
# =============================================================================
# train_diff.py, predict_diff.py, eval_diff.py がこのファイルを参照します。
# パスは実行時のカレントディレクトリからの相対パスで指定してください。

import os

# スクリプトの場所を基準にしたプロジェクトルート
_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
_PROJECT_ROOT = os.path.abspath(os.path.join(_SCRIPT_DIR, "..", "..", ".."))

# =============================================================================
# ===== 学習データ設定 (train_diff.py) =====
# =============================================================================
# DYNが変動している歌唱データ（WAVとVSQXのペア）
# VSQXにDYNの制御点が書き込まれている必要がある
# フォルダ内を再帰的に検索し、ファイル名が一致するペアを自動検出
TRAIN_WAV_DIR = os.path.join(_PROJECT_ROOT, "data", "wav_ALL")
TRAIN_VSQX_DIR = os.path.join(_PROJECT_ROOT, "data", "use_vsqx","IA")

# メモリ枯渇を防ぐための学習フレーム数の上限
MAX_TRAIN_FRAMES = 500000

# =============================================================================
# ===== 推定フェーズ設定 (predict_diff.py) =====
# =============================================================================
# DYNを推定したい対象のWAVファイル
TARGET_WAV = os.path.join(_PROJECT_ROOT, "data", "wav_ALL", "Test", "Test1.wav")

# 推定結果を書き込む元となるVSQXファイル (DYN部分が上書きされます)
TARGET_VSQX = os.path.join(_PROJECT_ROOT, "data", "vsqx_ALL", "Test", "Test1.vsqx")

# =============================================================================
# ===== 一括評価設定 (eval_diff.py) =====
# =============================================================================
# テスト対象のWAVフォルダ (再帰検索)
EVAL_WAV_DIR = os.path.join(_PROJECT_ROOT, "data", "wav_ALL", "Test")

# テスト対象のVSQXフォルダ (再帰検索、正解DYNが記録されているもの)
EVAL_VSQX_DIR = os.path.join(_PROJECT_ROOT, "data", "vsqx_ALL", "Test")

# 評価結果のExcel出力パス
EVAL_OUTPUT_EXCEL = os.path.join(_SCRIPT_DIR, "output", "diff_eval_results.xlsx")

# =============================================================================
# ===== 出力設定 =====
# =============================================================================
MODEL_DIR = os.path.join(_SCRIPT_DIR, "models")
MODEL_PATH = os.path.join(MODEL_DIR, "diff_dyn_model.pkl")
OUTPUT_DIR = os.path.join(_SCRIPT_DIR, "output")

# =============================================================================
# ===== 音響設定 =====
# =============================================================================
SR = 44100
HOP_LENGTH = 256

# =============================================================================
# ===== Melスペクトログラム設定 =====
# =============================================================================
N_MELS = 80  # メルフィルタバンク数

# =============================================================================
# ===== 時間差分モデル固有設定 =====
# =============================================================================
# 差分を計算するフレーム間隔 (1 = 隣接フレーム, 3 = 3フレーム先との差分)
# 大きいほどノイズに強くなるが、時間解像度が落ちる
DIFF_STEP = 15

# Ridge回帰の正則化パラメータ (大きいほど係数を抑制してモデルを安定化)
RIDGE_ALPHA = 5.0

# =============================================================================
# ===== 積分・復元設定 =====
# =============================================================================
# 漏れ積分 (Leaky Integrator) の漏れ係数
# 0.0 = 完全な積分 (ドリフトしやすい), 1.0 = 変化を完全に無視
# 推奨: 0.001 ~ 0.01
LEAK_RATE = 0.005

# 積分の初期値 (ノート開始時のDYNデフォルト値)
DYN_DEFAULT = 64

# 出力振幅倍率 (モデル出力のΔDYNに掛ける倍率)
# モデルは保守的に小さな値を出すため、倍率で補正する。
# 学習終了時に推奨倍率が表示されるので、その値を参考に設定する。
# 1.0 = モデル生出力。大きくするとダイナミクスが強まる。
DIFF_OUTPUT_SCALE = 2.0

# ステップリミッター: 1ステップあたりのΔDYN予測値の最大絶対値
# 音素変化による周波数の激変をDYN変動と誤認するのを防ぐ。
# この値を超える予測はクリッピングされる。
# 例: 5.0 → 1ステップで最大±5の変動のみ許容
DELTA_DYN_CLAMP = 5.0

# =============================================================================
# ===== 動的アンカー設定 (ノート開始DYNの推定) =====
# =============================================================================
# ノート開始時のDYNを64固定ではなく、学習データから自動獲得した
# 線形回帰モデルを使って、音量(Melパワー)から動的に推定する。
# これにより「ノートの出だしが強い → DYNが高い」という関係を反映できる。
DYNAMIC_ANCHOR_ENABLED = True

# =============================================================================
# ===== ノート境界設定 =====
# =============================================================================
# ノートの開始・終了からこのフレーム数分は推定をスキップし、補間する
# 子音の発音や音量の急激な変化によるスパイクを抑制するため
NOTE_BOUNDARY_SKIP_FRAMES = 2

# 長い休符 (この秒数以上) ではDYNをデフォルト値 (64) に戻す
REST_THRESHOLD_SEC = 0.01

# =============================================================================
# ===== 音量ガード設定 (無声子音トラップ回避) =====
# =============================================================================
# ノート内であっても、Mel全帯域平均パワーがこの値(dB)以下のフレームは
# 無声子音や息継ぎとみなし、ΔDYNの予測を0(変化なし)として無視する。
# -80 = ほぼ無音のみ除外, -65 = 子音区間も広く除外
MEL_POWER_THRESHOLD_DB = -60.0

# =============================================================================
# ===== 平滑化設定 =====
# =============================================================================
# Savitzky-Golayフィルタのパラメータ
SAVGOL_WINDOW = 31   # フレーム数 (奇数)
SAVGOL_POLYORDER = 3  # 多項式の次数
