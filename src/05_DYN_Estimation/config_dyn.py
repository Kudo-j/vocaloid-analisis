SAVGOL_POLYORDER = 3  # 多項式の次数

# =============================================================================
# ===== ノート間補間設定 =====
# =============================================================================
# 長い休符 (この秒数以上) ではDYNをデフォルト値 (64) に戻す
REST_THRESHOLD_SEC = 0.1

# デフォルトDYN値 (ノート間補間のターゲット)
DYN_DEFAULT = 64

# =============================================================================
# ===== 出力スケーリング設定 (飽和対策) =====
# =============================================================================
# 推定されたDYNの変動幅（64からの差分）に対する倍率。
# 1.0 がモデルの生出力。上限(127)や下限(0)に張り付く場合は、0.5 や 0.3 などに下げてください。
DYN_OUTPUT_SCALE = 0.07

# =============================================================================
# ===== 多項式特徴量設定 =====
# =============================================================================
# ΔMel → DYN 変換の線形モデルに多項式特徴量を使用するか
