# ===== Melスペクトログラム設定 (ベースラインモデルの出力) =====
# =============================================================================
N_MELS = 80  # メルフィルタバンク数

# =============================================================================
# ===== 平滑化設定 =====
# =============================================================================
# Savitzky-Golayフィルタのパラメータ
# window_length: 奇数。大きいほど滑らか。小さいほどDYNの急峻な変化を保持。
# polyorder: 多項式の次数。window_length より小さい必要がある。
